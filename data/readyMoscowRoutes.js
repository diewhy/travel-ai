function buildText(theme, variant, stops) {
  const stopsText = stops
    .map(
      (stop, index) =>
        `**${index + 1}. ${stop.name}**\n${stop.description}\n\n**Задание:** ${stop.task}`
    )
    .join('\n\n')

  return `**${theme.title}**\n\n${theme.history}\n\n**Формат:** ${variant.label}\n**Продолжительность:** ${variant.duration}\n**Точек:** ${stops.length}\n\n${stopsText}`
}

